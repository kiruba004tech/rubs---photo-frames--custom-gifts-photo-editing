function generateSizes(basePrice: number): SizePriceOption[] {
  return STANDARD_FRAME_SIZES.map((size) => {
    const meta = FRAME_SIZE_DETAILS[size];
    const computedPrice = Math.round((basePrice * meta.baseMultiplier) / 10) * 10 - 1; // e.g. 299, 499, 699
    return {
      size,
      label: meta.label,
      price: computedPrice,
      dimensionsCm: meta.dimensionsCm,
      aspectRatio: meta.aspectRatio,
      recommendedFor: meta.recommendedFor,
    };
  });
}

